-- Disposable local/CI database only. No human accounts, messages or emails.
begin;
create function pg_temp.assert_true(ok boolean, label text) returns void language plpgsql as $$
begin if ok is distinct from true then raise exception 'FAIL: %',label; end if; end $$;
create function pg_temp.expect_code(statement text, expected text) returns void language plpgsql as $$
begin
  begin execute statement; exception when others then if sqlstate=expected then return; end if; raise; end;
  raise exception 'Expected SQLSTATE %: %',expected,statement;
end $$;
insert into auth.users(id) select ('00000000-0000-4000-8000-'||lpad(n::text,12,'0'))::uuid from generate_series(1,12) n;
update public.citizens set handle='test_citizen_'||right(id::text,2),onboarding_completed_at=now();
select pg_temp.assert_true(not has_table_privilege('authenticated','public.conversation_threads','INSERT'),'client thread insertion still denied');
select pg_temp.assert_true(not has_table_privilege('authenticated','public.thread_members','INSERT'),'client member insertion still denied');
select pg_temp.assert_true(not has_table_privilege('authenticated','public.conversation_requests','INSERT'),'invitations are RPC-only');
select pg_temp.assert_true(not has_function_privilege('anon','public.request_conversation(text)','EXECUTE'),'anonymous invitation denied');
set local role authenticated;
set local request.jwt.claims='{"sub":"00000000-0000-4000-8000-000000000001","is_anonymous":false}';
