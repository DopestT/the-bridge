select pg_temp.assert_true(status='declined' and thread_id is null,'recipient can decline') from public.respond_conversation_request(current_setting('netizens.test_request')::uuid,'decline');
set local request.jwt.claims='{"sub":"00000000-0000-4000-8000-000000000001","is_anonymous":false}';
select pg_temp.expect_code('select public.request_conversation(''test_citizen_02'')','42501');
-- The recipient may independently invite the original requester later.
set local request.jwt.claims='{"sub":"00000000-0000-4000-8000-000000000002","is_anonymous":false}';
select set_config('netizens.test_request',request_id::text,true) from public.request_conversation('test_citizen_01');
set local request.jwt.claims='{"sub":"00000000-0000-4000-8000-000000000001","is_anonymous":false}';
