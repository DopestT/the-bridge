select pg_temp.assert_true(thread_id::text=current_setting('netizens.test_thread'),'acceptance replay reuses thread') from public.respond_conversation_request(current_setting('netizens.test_request')::uuid,'accept');
select pg_temp.assert_true(status='accepted' and thread_id::text=current_setting('netizens.test_thread'),'existing direct conversation reused') from public.request_conversation('test_citizen_02');
